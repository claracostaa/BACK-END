// Array
// um array é uma lista que pode armarzenar vários valores.

let frutas = ["Morango", "Banana", "Uva"];
// let frutas = ["0", "1", "2"]
console.log(frutas[1])

// Podemos adicionar itens!, sem alterar o array diretamente
frutas.push("Laranja"); // Adiciona ao final
console.log(frutas);
frutas.pop(); // remove do final (no nosso caso a laranja)
console.log(frutas);

